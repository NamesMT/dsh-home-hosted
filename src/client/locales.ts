/** Substitute `{name}` placeholders; a missing param is left verbatim. */
export function interpolate(text: string, params?: Record<string, unknown>): string {
  if (params === undefined) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match)
}

/** English-only translator used when no locale service is available. */
export const englishTranslator: TranslateFn = (key, params) =>
  interpolate(en[key as keyof typeof en] ?? key, params)

/** Bind the service's namespace, falling back to the bundled English copy. */
export function createTranslator(locale?: LocaleService): TranslateFn {
  if (locale !== undefined) {
    try {
      const bound = locale.bind(LOCALE_NS)
      if (typeof bound === 'function') return bound
    }
    catch {
      // Fall through to the bundled copy.
    }
  }
  return englishTranslator
}

/**
 * Wrap a translator that is out of our control (the framework's injected `t`
 * seat) so a missing dictionary — a result equal to the key — falls back to
 * the bundled copy instead of rendering the raw locale key.
 */
export function resolveTranslator(
  candidate?: TranslateFn,
  fallback: TranslateFn = englishTranslator,
): TranslateFn {
  if (candidate === undefined) return fallback
  return (key, params) => {
    let value: string | undefined
    try {
      value = candidate(key, params)
    }
    catch {
      value = undefined
    }
    if (value === undefined || value.length === 0 || value === key) return fallback(key, params)
    return value
  }
}
